/**
 * Renderiza um ícone SVG oficial do Lucide
 * @param {string} name - Nome do ícone Lucide
 * @param {object} options - Opções de renderização (width, height, stroke, strokeWidth, className, extraAttrs)
 * @returns {string} Código SVG string
 */
export function lucide(name, options = {}) {
  const paths = LUCIDE_PATHS[name];
  if (!paths) {
    console.warn(`[lucide] Ícone "${name}" não encontrado.`);
    return '';
  }

  const width = options.width || options.size || 24;
  const height = options.height || options.size || 24;
  const stroke = options.stroke || 'currentColor';
  const strokeWidth = options.strokeWidth !== undefined ? options.strokeWidth : 2;
  const className = options.className ? `class="${options.className}"` : '';
  const extraAttrs = options.extraAttrs ? ` ${options.extraAttrs}` : '';

  return `
    <svg 
      xmlns="http://www.w3.org/2000/svg" 
      width="${width}" 
      height="${height}" 
      viewBox="0 0 24 24" 
      fill="none" 
      stroke="${stroke}" 
      stroke-width="${strokeWidth}" 
      stroke-linecap="round" 
      stroke-linejoin="round"
      ${className}${extraAttrs}
    >
      ${paths}
    </svg>
  `.trim();
}
